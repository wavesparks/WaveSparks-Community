function daysAgo(days: number) {
  const next = new Date();
  next.setDate(next.getDate() - days);
  return next.toISOString();
}

function hoursAgo(hours: number) {
  const next = new Date();
  next.setHours(next.getHours() - hours);
  return next.toISOString();
}

